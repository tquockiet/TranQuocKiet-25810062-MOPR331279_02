fun main() {
    // 1. Đoạn đếm ngược từ 10 về 1 bắt buộc dùng while
    println("--- Đếm ngược từ 10 về 1 ---")
    var dem = 10
    while (dem >= 1) {
        println(dem)
        dem--
    }

    // 2. Đoạn in dòng cố định 5 lần dùng repeat
    println("\n--- In dòng cố định 5 lần ---")
    repeat(5) {
        println("Lập trình di động rất thú vị!")
    }
}

